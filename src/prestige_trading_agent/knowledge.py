def _package_block() -> str:
    lines: list[str] = []
    for p in PACKAGES:
        lines.append(
            f"- {p.name} | {p.price} | {p.billing}\n"
            f"  เหมาะกับ: {p.audience}\n"
            f"  ได้รับ: {p.includes}\n"
            f"  ทดลอง: {p.trial} | โบนัส: {p.bonus} | สิทธิ์: {p.access}\n"
            f"  เงื่อนไข: {p.conditions}\n"
            f"  ช่องทาง: {p.checkout}"
        )
    return "\n".join(lines)


def _faq_block() -> str:
    lines: list[str] = []
    for i, faq in enumerate(FAQS, start=1):
        lines.append(
            f"{i}. Q: {faq.question}\n   (อาจถามว่า: {faq.variants})\n"
            f"   A: {faq.answer}\n   ต่อ: {faq.follow_up}"
        )
    return "\n".join(lines)


